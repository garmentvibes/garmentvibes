export function getRetailProductBySlug(slug: string) {
  return RETAIL_PRODUCTS.find((p) => p.slug === slug);
}

export function getRetailProductById(id: string) {
  return RETAIL_PRODUCTS.find((p) => p.id === id);
}

export function getRetailProductsByCategory(category: string) {
  return RETAIL_PRODUCTS.filter((p) => p.category === category);
}

// Fields are ordered by weight — a name match outranks a category match.
const retailSearchFields = (p: RetailProduct) => [
  p.name,
  p.brand,
  p.subcategory,
  p.category,
  p.colors.join(" "),
];

export function searchRetailProducts(query: string, limit?: number) {
  if (!query.trim()) return [];
  return fuzzySearch(query, RETAIL_PRODUCTS, retailSearchFields, limit);
}

export function getRelatedRetailProducts(product: RetailProduct, limit = 4) {
  return RETAIL_PRODUCTS.filter(
    (p) => p.id !== product.id && (p.category === product.category || p.subcategory === product.subcategory)
  ).slice(0, limit);
}
